# Завдання №6. Периметр прямокутника.

length = int(input("Введіть довжину прямокутника: "))               # Програма просить користувача ввести дані
width = int(input("Введіть ширину прямокутника: "))
perimeter = (length * 2) + (width * 2)                              # Програма вираховує периметр
print("Периметр:", perimeter)                                       # Програма виводить результат в термінал