# Завдання №4. Розрахунок знижки.

price = float(input("Введіть ціну товару: "))           # Програма просить користувача ввести дані
discount = float(input("Введіть знижку (%): "))
final_price = price - (price * discount / 100)          # Програма вираховує результат - ціну зі знижкою
print("Ціна зі знижкою:", final_price)                  # Програма виводить результат в термінал