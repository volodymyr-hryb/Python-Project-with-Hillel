# Завдання №5. Остання цифра числа.

number = int(input("Введіть ціле число: "))             # Програма просить користувача ввести дані
last_num = number % 10                                  # Програма знаходить останню цифру у числі
print("Остання цифра:", last_num)                       # Програма виводить результат в термінал