# Завдання №2. Середнє трьох чисел.

num_1 = float(input("Введіть перше число: "))          # Програма просить користувача ввести дані
num_2 = float(input("Введіть друге число: "))
num_3 = float(input("Введіть третє число: "))
average = (num_1 + num_2 + num_3) / 3                # Програма вираховує середнє значення
print("Середнє:", average)                           # Програма виводить результат в термінал