# Завдання №3. Перетворення хвилин у години.

total_min = int(input("Введіть кількість хвилин: "))        # Програма просить користувача ввести дані
hours = total_min // 60                                     # Програма вираховує кількість годин
minutes = total_min - hours * 60                            # Програма вираховує кількість хвилин
print(hours, "години", minutes, "хвилин")                   # Програма виводить результат в термінал